// Pulls the latest Rectitudes posts from the Substack RSS feed into data/posts.js.
// If the fetch fails, the existing file is left alone so the site never loses its list.
import { writeFile, mkdir } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

// With sharp installed, cover images are shrunk to small WebP files; without it they are saved as they come.
let sharp = null;
try { sharp = (await import('sharp')).default; } catch { /* optional */ }

const FEED = process.env.FEED_URL || 'https://rectitudes.substack.com/feed';
const COVERS = new URL('../assets/posts/', import.meta.url);
const UA = { 'User-Agent': 'Mozilla/5.0 (zayd.fun feed sync)' };
const OUT = new URL('../data/posts.js', import.meta.url);

const decode = (s) => s
  .replace(/<!\[CDATA\[([\s\S]*?)\]\]>/g, '$1')
  .replace(/&amp;/g, '&').replace(/&lt;/g, '<').replace(/&gt;/g, '>')
  .replace(/&quot;/g, '"').replace(/&#8217;|&#039;|&#39;/g, "'").replace(/&#8220;|&#8221;/g, '"');
const strip = (s) => decode(s).replace(/<[^>]+>/g, ' ').replace(/\s+/g, ' ').trim();
const pick = (block, tag) => {
  const m = block.match(new RegExp(`<${tag}[^>]*>([\\s\\S]*?)</${tag}>`));
  return m ? m[1] : '';
};

// The post's cover image: the feed's enclosure, or the first picture in the article.
function coverUrl(it) {
  const enc = it.match(/<enclosure[^>]*\burl="([^"]+)"/);
  if (enc) return decode(enc[1]);
  const img = decode(pick(it, 'content:encoded')).match(/<img[^>]+src="([^"]+)"/);
  return img ? img[1] : '';
}

// Downloads the cover into assets/posts/ so the page can dither it from its own domain.
async function saveCover(url, link) {
  try {
    const slug = (new URL(link).pathname.split('/').filter(Boolean).pop() || 'post').toLowerCase().replace(/[^a-z0-9-]+/g, '-').slice(0, 80);
    const r = await fetch(url, { headers: UA });
    if (!r.ok) throw new Error(`image returned ${r.status}`);
    const buf = Buffer.from(await r.arrayBuffer());
    await mkdir(fileURLToPath(COVERS), { recursive: true });
    let name;
    if (sharp) {
      name = `${slug}.webp`;
      await sharp(buf).rotate().resize({ width: 900, withoutEnlargement: true }).webp({ quality: 72 }).toFile(fileURLToPath(new URL(name, COVERS)));
    } else {
      const type = r.headers.get('content-type') || '';
      name = `${slug}.${/png/.test(type) ? 'png' : /webp/.test(type) ? 'webp' : /avif/.test(type) ? 'avif' : 'jpg'}`;
      await writeFile(new URL(name, COVERS), buf);
    }
    return `assets/posts/${name}`;
  } catch (err) {
    console.warn(`No cover for ${link}: ${err.message}`);
    return '';
  }
}

try {
  const res = await fetch(FEED, { headers: UA });
  if (!res.ok) throw new Error(`feed returned ${res.status}`);
  const xml = await res.text();
  const items = [...xml.matchAll(/<item>([\s\S]*?)<\/item>/g)].map((m) => m[1]);
  const posts = (await Promise.all(items.slice(0, 6).map(async (it) => {
    const excerpt = strip(pick(it, 'description'));
    const post = {
      title: strip(pick(it, 'title')),
      url: strip(pick(it, 'link')),
      date: new Date(strip(pick(it, 'pubDate'))).toISOString(),
      excerpt: excerpt.length > 170 ? excerpt.slice(0, 167).trimEnd() + '...' : excerpt,
    };
    const img = coverUrl(it);
    if (img && post.url) { const cover = await saveCover(img, post.url); if (cover) post.cover = cover; }
    return post;
  }))).filter((p) => p.title && p.url);
  if (!posts.length) throw new Error('no posts found in feed');
  await writeFile(OUT, `/* Generated by scripts/fetch-posts.mjs. Do not edit by hand. */\nwindow.POSTS = ${JSON.stringify(posts, null, 2)};\n`);
  console.log(`Wrote ${posts.length} posts`);
} catch (err) {
  console.warn(`Skipped feed sync: ${err.message}`);
}
